export function ruKeyName(name: string, display: string): string {
  if (!ru()) return display;
  return NAMES[display.toLowerCase()] ?? NAMES[name.toLowerCase()] ?? display;
}

export function ruKeyHelp(name: string, help: string): string {
  if (!ru()) return help;
  return HELPS[name] ?? HELPS[name.toLowerCase()] ?? help;
}

