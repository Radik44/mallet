"""Builds the installer's language data from installer/strings/<code>.json and
installer/license/<code>.txt:

- installer/strings.nsh - LangString lines for every language (component names,
  descriptions, progress, licence page texts); included by installer.nsi after the
  languages, so `${LANG_…}` is defined there.
- installer/license/build/<code>.txt - the licence as the licence page shows it:
  paragraphs unwrapped, CRLF, UTF-16LE without BOM (read with FileReadUTF16LE).
- installer/license-extract.nsh - the MALLET_EXTRACT_LICENSE macro that extracts the
  file of the chosen language at run time; included by hooks.nsh at the top of the
  script (the page function is compiled before the languages exist), so it matches
  $LANGUAGE by LCID.

Every language of the installer (tauri.conf.json → bundle.windows.nsis.languages) needs the
same keys and a licence text; the English licence is the repository's LICENSE, the others
are translations of it. Run after editing any of the inputs:

    python apps/editor/src-tauri/installer/make_strings.py
"""

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
BOM = b"\xef\xbb\xbf"
# Dictionary code → (NSIS language name of the Modern UI language files, Windows LCID).
LANGS = {
    "en": ("ENGLISH", 1033),
    "ru": ("RUSSIAN", 1049),
    "de": ("GERMAN", 1031),
    "fr": ("FRENCH", 1036),
    "es": ("SPANISH", 1034),
    "pt-BR": ("PORTUGUESEBR", 1046),
    "pl": ("POLISH", 1045),
    "tr": ("TURKISH", 1055),
    "uk": ("UKRAINIAN", 1058),
    "zh-CN": ("SIMPCHINESE", 2052),
    "ja": ("JAPANESE", 1041),
}


def runtime_text(text: str, code: str) -> str:
    """Paragraphs on one line each (the text box wraps them itself), blank lines kept, CRLF."""
    joiner = "" if code in ("zh-CN", "ja") else " "
    paras: list[str] = []
    cur: list[str] = []
    for line in text.replace("\r\n", "\n").split("\n"):
        if line.strip():
            cur.append(line.strip())
        else:
            if cur:
                paras.append(joiner.join(cur))
                cur = []
            paras.append("")
    if cur:
        paras.append(joiner.join(cur))
    while paras and paras[-1] == "":
        paras.pop()
    return "\r\n".join(paras) + "\r\n"


def nsis_escape(text: str) -> str:
    return text.replace("$", "$$").replace('"', '$\\"').replace("\r", "").replace("\n", "$\\n")


def main() -> int:
    strings_dir = HERE / "strings"
    license_dir = HERE / "license"
    (license_dir / "build").mkdir(exist_ok=True)
    keys = None
    out = [
        "; Generated by installer/make_strings.py from installer/strings/*.json - do not edit by hand.",
        "",
    ]
    problems = 0
    for code, (lang, _lcid) in LANGS.items():
        sp = strings_dir / f"{code}.json"
        lp = license_dir / f"{code}.txt"
        if not sp.exists() or not lp.exists():
            print(f"{code}: missing {'strings' if not sp.exists() else ''} {'license' if not lp.exists() else ''}")
            problems += 1
            continue
        data = json.loads(sp.read_text(encoding="utf-8-sig"))
        if keys is None:
            keys = list(data.keys())
        elif list(data.keys()) != keys:
            print(f"{code}: keys differ from {list(LANGS)[0]}: {sorted(set(data) ^ set(keys))}")
            problems += 1
        text = lp.read_text(encoding="utf-8-sig")
        lp.write_bytes(BOM + text.replace("\r\n", "\n").encode("utf-8"))
        (license_dir / "build" / f"{code}.txt").write_bytes(runtime_text(text, code).encode("utf-16-le"))
        out.append(f"; {code}")
        for k, v in data.items():
            if not isinstance(v, str) or not v:
                print(f"{code}: {k} is empty")
                problems += 1
                continue
            out.append(f'LangString {k} ${{LANG_{lang}}} "{nsis_escape(v)}"')
        out.append("")
    (HERE / "strings.nsh").write_bytes(BOM + "\n".join(out).encode("utf-8"))

    ext = [
        "; Generated by installer/make_strings.py - do not edit by hand.",
        "!macro MALLET_EXTRACT_LICENSE",
        "  ${Switch} $LANGUAGE",
    ]
    for code, (_lang, lcid) in LANGS.items():
        ext.append(f"    ${{Case}} {lcid}")
        ext.append(f'      File "/oname=$PLUGINSDIR\\mallet-license.txt" "${{MALLET_INSTALLER_DIR}}\\license\\build\\{code}.txt"')
        ext.append("      ${Break}")
    ext.append("    ${Default}")
    ext.append('      File "/oname=$PLUGINSDIR\\mallet-license.txt" "${MALLET_INSTALLER_DIR}\\license\\build\\en.txt"')
    ext.append("  ${EndSwitch}")
    ext.append("!macroend")
    ext.append("")
    (HERE / "license-extract.nsh").write_bytes(BOM + "\n".join(ext).encode("utf-8"))
    print(f"strings.nsh: {len(LANGS)} languages, {len(keys or [])} keys each, {problems} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
